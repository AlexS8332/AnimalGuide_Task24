// Slug — безопасное имя файла из произвольной строки тем же способом, что
// у save_to_file: строчная латиница, цифры, «-» и «_», кириллица —
// транслитом, без точек и разделителей каталогов. Пустой результат — из
// строки имени не получилось. Нужен другим серверам, которые сохраняют
// файлы (блокнот натуралиста), чтобы правило имени было одно.
func Slug(s string) string { return exportSlug(s) }
