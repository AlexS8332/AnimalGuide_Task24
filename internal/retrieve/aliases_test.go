func TestStem(t *testing.T) {
	same := [][2]string{
		{"кошачий", "кошачьего"}, {"медведь", "медведя"}, {"медведь", "медведями"}, {"барс", "барса"},
		{"палласов", "палласова"}, {"палласов", "палласа"}, {"хаус", "хаусов"}, {"снежный", "снежных"},
		{"леопард", "леопардов"}, {"малая", "малых"}, {"панда", "панд"}, {"рысь", "рыси"}, {"солонгой", "солонгоя"},
		{"Ёж", "еж"},
	}
	for _, p := range same {
		if !sameStem(stem(p[0]), stem(p[1])) {
			t.Errorf("%s и %s — разные основы: %s, %s", p[0], p[1], stem(p[0]), stem(p[1]))
		}
	}
	diff := [][2]string{{"барс", "барсук"}, {"белый", "белогрудый"}, {"кот", "кошка"}, {"волк", "волков"[:4] + "ан"}}
	for _, p := range diff {
		if sameStem(stem(p[0]), stem(p[1])) {
			t.Errorf("%s и %s — одна основа %s", p[0], p[1], stem(p[0]))
		}
	}
}

// TestExpandRealCorpus — таблица раскрытия на настоящем корпусе: синонимы,
// падежи, общие слова, канон в запросе.
func TestExpandRealCorpus(t *testing.T) {
	a := realAliases(t)
	cases := []struct {
		q    string
		want []string // раскрытое: «синоним → канон»; nil — ничего
		add  string   // что должно появиться в запросе
	}{
		{"Сколько часов в день кошачий медведь тратит на еду?", []string{"кошачий медведь → малая панда"}, "малая панда Ailurus fulgens"},
		{"Что ест кошачьего медведя?", []string{"кошачьего медведя → малая панда"}, "малая панда"},
		{"С какой скоростью может бежать степная лисица?", []string{"степная лисица → корсак"}, "корсак Vulpes corsac"},
		{"Сколько хромосом у палласова кота?", []string{"палласова кота → манул"}, "манул Otocolobus manul"},
		{"Сколько хаусов обитает на территории России?", []string{"хаусов → камышовый кот"}, "камышовый кот"},
		{"Сколько снежных леопардов оставалось в дикой природе?", []string{"снежных леопардов → ирбис"}, "ирбис Panthera uncia"},
		{"Где живёт гиена?", []string{"гиена → полосатая гиена"}, "полосатая гиена"},
		{"Чем питается выдра?", []string{"выдра → речная выдра"}, "речная выдра"},
		{"Какая выдра самая крупная?", []string{"выдра → речная выдра"}, "речная выдра"},
		{"Где обитает Ailurus fulgens?", []string{"Ailurus fulgens → малая панда"}, "малая панда"},
		// Канон в запросе — ничего не добавляется.
		{"Сколько весит малая панда?", nil, ""},
		{"Кошачий медведь, он же малая панда, — сколько весит?", nil, ""},
		{"Сколько весит белый медведь?", nil, ""},
		// Общие однословные синонимы (правило 2): «медведь» есть в названиях
		// других видов, «барс» — в «амурском барсе», «рысь» — в «степной рыси».
		{"Сколько весит медведь?", nil, ""},
		{"Где водится барс?", nil, ""},
		{"Чем питается рысь?", nil, ""},
		// Однословный синоним после определения (правило 3): другой вид.
		{"Сколько весит пятнистая гиена?", nil, ""},
		{"Чем питается морская выдра?", nil, ""},
		{"Где живёт чёрный медведь?", nil, ""},
		// «Барсук» — не «барс».
		{"Чем питается барсук?", nil, ""},
		// Длинное раньше короткого: «амурский барс» — леопард, не ирбис.
		{"Сколько осталось амурских барсов?", []string{"амурских барсов → дальневосточный леопард"}, "дальневосточный леопард"},
		{"Где живёт белогрудый медведь?", []string{"белогрудый медведь → гималайский медведь"}, "гималайский медведь"},
		{"Сколько весит фосса?", nil, ""},
		// Короткая основа — только точной формой (правило 5): «долю» не «долов».
		{"Какую долю рациона харзы составляют копытные?", nil, ""},
		{"Где живёт долов?", []string{"долов → красный волк"}, "красный волк Cuon alpinus"},
	}
	for _, c := range cases {
		got, list := a.Expand(c.q)
		if strings.Join(list, "; ") != strings.Join(c.want, "; ") {
			t.Errorf("%q: раскрыто %q, ждали %q", c.q, list, c.want)
			continue
		}
		if c.want == nil && got != c.q {
			t.Errorf("%q: запрос изменён: %q", c.q, got)
		}
		if c.add != "" && (!strings.HasPrefix(got, strings.TrimSpace(c.q)) || !strings.Contains(got, c.add)) {
			t.Errorf("%q: запрос %q, ждали дописанное %q", c.q, got, c.add)
		}
	}
}

func TestSpecies(t *testing.T) {
	a := realAliases(t)
	cases := map[string]string{
		"Где в России водится харза?":                   "харза",
		"Сколько весит каракал?":                        "каракал",
		"Какой статус у манула в Красном списке МСОП?":  "манул",
		"Кто тяжелее — харза или барханный кот?":        "харза, барханный кот",
		"Сравни кошачьего медведя и белого медведя":     "малая панда, белый медведь",
		"А сколько она весит?":                          "",
		"Какую долю рациона харзы составляют копытные?": "харза",
		"Сколько весит медведь?":                        "",
		"Что знаешь про волка и красного волка?":        "волк, красный волк",
		"Где живёт Otocolobus manul и чем он питается?": "манул",
	}
	for text, want := range cases {
		if got := strings.Join(a.Species(text), ", "); got != want {
			t.Errorf("%q: %q, ждали %q", text, got, want)
		}
	}
	var nilA *Aliases
	if nilA.Species("манул") != nil {
		t.Error("пустой словарь нашёл вид")
	}
	if q, l := (&Aliases{}).Expand("манул"); q != "манул" || l != nil {
		t.Error("пустой словарь раскрыл")
	}
}

// TestAliasesLiteralAndConflict — словарь литералом (без корпуса) и
// синоним с двумя видами.
func TestAliasesLiteralAndConflict(t *testing.T) {
	a := &Aliases{Canon: map[string]string{"зверь": "первый", "первый": "первый", "второй": "второй"}}
	if q, l := a.Expand("где живёт зверь"); len(l) != 1 || q != "где живёт зверь первый" {
		t.Fatalf("литерал: %q %v", q, l)
	}
	docs := []corpus.Doc{
		{ID: "a", Title: "Альфа", Species: &corpus.Species{Ru: "альфа", Aliases: []string{"общий зверь"}}},
		{ID: "b", Title: "Бета", Species: &corpus.Species{Ru: "бета", Aliases: []string{"общий зверь"}, Latin: "Beta beta"}},
		{ID: "c", Title: "Гамма", Species: &corpus.Species{}},
		{ID: "d", Title: "Обзор"},
	}
	b := AliasesOf(docs)
	if _, ok := b.Canon["общий зверь"]; ok {
		t.Fatal("синоним двух видов остался в словаре")
	}
	if b.Canon["гамма"] != "гамма" || b.Latin["бета"] != "Beta beta" || b.Canon["beta beta"] != "бета" {
		t.Fatalf("словарь: %v %v", b.Canon, b.Latin)
	}
}

