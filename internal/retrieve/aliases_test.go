func TestIntroNamesAndCatVariant(t *testing.T) {
	got := introNames("Камышовый кот, или хаус, или камышовая кошка, или болотная рысь (лат. Felis chaus) — вид.")
	if strings.Join(got, "; ") != "хаус; камышовая кошка; болотная рысь" {
		t.Fatalf("вступление: %q", got)
	}
	if got := introNames("Красный волк, или горный волк (устаревшие названия: гималайский волк или буанзу) (лат. Cuon alpinus)"); strings.Join(got, "; ") != "горный волк" {
		t.Fatalf("скобки: %q", got)
	}
	if got := introNames("Малая панда, кошачий медведь, красная (рыжая) панда (лат. Ailurus fulgens)"); got != nil {
		t.Fatalf("без «или»: %q", got)
	}
	for in, want := range map[string]string{"барханный кот": "барханная кошка", "камышовая кошка": "камышовый кот", "дикий кот": "дикая кошка",
		"палласов кот": "палласова кошка", "манул": "", "кот палласа": ""} {
		if got := catVariant(in); got != want {
			t.Errorf("%q → %q, ждали %q", in, got, want)
		}
	}
}
