// System — роль извлекателя. Главное в промпте — граница между адресатами
// (П-6): модель охотно кладёт всё в одно место, и без явной границы «мне
// удобнее списком» становится записью памяти, которая на форму ответа
// почти не влияет. В сомнительном случае — разовая правка.
func System(t Targets) string {
	var b strings.Builder
	b.WriteString(`Ты ведёшь память и профиль справочника по животным, который разговаривает с человеком. После каждой реплики ты решаешь, что из сказанного стоит сохранить и куда положить. Адресаты различаются не важностью, а тем, о чём они и сколько живут.
`)
	if t.Profile {
		b.WriteString(`
ПРОФИЛЬ — как разговаривать с этим человеком: уровень изложения, длина, форма, обращение, латынь, единицы, эмодзи, ограничения. Это правила формы, а не сведения. Поля и допустимые значения:
`)
		for _, f := range profile.Fields() {
			vals := make([]string, len(f.Options))
			for i, o := range f.Options {
				vals[i] = fmt.Sprintf("%s (%s)", o.Value, o.Title)
			}
			fmt.Fprintf(&b, "- %s — %s: %s\n", f.Key, f.Title, strings.Join(vals, ", "))
		}
	}
	if t.Long {
		b.WriteString("\nДОЛГОВРЕМЕННАЯ ПАМЯТЬ (layer \"long\") — что известно о человеке вообще и пригодится в следующих разговорах: имя, возраст ребёнка, для чего человеку справочник, интересы («любит сов»), постоянные договорённости.\n")
	}
	if t.Work {
		b.WriteString("\nРАБОЧАЯ ПАМЯТЬ (layer \"work\") — всё про текущую подборку: для чего она, сколько видов, какие условия поставил человек. Пропадает вместе с подборкой.\n")
	}
	if t.Facts {
		b.WriteString("\nКАРТОЧКА ФАКТОВ (\"facts\") — что сказано и решено именно в этой ветке разговора и не относится ни к человеку вообще, ни к подборке: о чём сейчас разговор, что сравниваем, о чём договорились на этот разговор.\n")
	}
	b.WriteString(`
Сведения о самих животных (латынь, ареал, питание, размеры, статус охраны) не записывай никуда: их берут из источников, а не из разговора.

Формат ответа — один объект JSON без пояснений:
{"profile": {"set": [{"field": "length", "value": "short", "scope": "always", "quote": "дословно из реплики"}], "limits": [{"text": "чего не делать", "scope": "always", "quote": "дословно из реплики"}]},
 "memory": {"set": [{"layer": "long", "key": "ключ", "value": "значение"}], "delete": [{"layer": "long", "key": "ключ"}]},
 "facts": {"set": [{"key": "ключ", "value": "значение"}], "delete": ["ключ"]}}
Пустые списки — нормальный и частый ответ.

Граница между адресатами:
- «Пиши мне покороче» — профиль (manner). «Я готовлю доклад о совах» — долговременная память, если это про человека, рабочая — если про текущую подборку. «Давай сейчас только про повадки» — карточка фактов.
- «Сделай таблицу» про конкретный ответ — разовая правка профиля (scope "once"), а не запись в память.
- Правка профиля без "quote" отбрасывается; цитата — дословный кусок ТЕКУЩЕЙ реплики пользователя, не ответа справочника.
- "scope": "always" — только когда человек говорит о себе вообще («всегда», «впредь», «мне удобнее», «мне 8 лет», «давай на ты»); "once" — просьба про этот ответ («а теперь покороче»). Сомневаешься — "once": неверно закреплённое предпочтение испортит все следующие разговоры.
- Значение поля — только из перечня. Своих значений не выдумывай.
- Поля профиля не дублируй в память и в карточку фактов.
- Ключ памяти и факта — короткое существительное в нижнем регистре; существующие ключи переиспользуй дословно, новое значение замещает старое.
- Записывай то, что сказал или решил пользователь. Предложение справочника без согласия пользователя — не решение.
- Если пользователь передумал — новое значение по тому же ключу; отменил без замены — "delete".`)
	if !t.Profile {
		b.WriteString("\n\nПрофиль в этом разговоре не ведётся: секции \"profile\" в ответе быть не должно.")
	}
	if !t.Long && !t.Work {
		b.WriteString("\n\nСлои памяти выключены: секции \"memory\" в ответе быть не должно.")
	} else if !t.Long {
		b.WriteString("\n\nДолговременная память выключена: слоя \"long\" в ответе быть не должно.")
	} else if !t.Work {
		b.WriteString("\n\nРабочей памяти сейчас нет (подборка не идёт): слоя \"work\" в ответе быть не должно.")
	}
	if !t.Facts {
		b.WriteString("\n\nКарточка фактов выключена: секции \"facts\" в ответе быть не должно.")
	}
	return b.String()
}

// request — что уходит извлекателю: адресаты целиком, хвост разговора без
// содержимого источников и новая реплика.
func request(in Input) string {
	var b strings.Builder
	if in.Targets.Profile {
		b.WriteString("=== Профиль (как разговаривать с человеком) ===\n" + in.Profile.Describe() + "\n")
		if hint := repeatedAsks(in.Profile); hint != "" {
			b.WriteString(hint)
		}
		b.WriteString("\n")
	}
	if in.Targets.Long {
		b.WriteString("=== Долговременная память ===\n" + in.Long.Render() + "\n\n")
	}
	if in.Targets.Work {
		title := ""
		if in.Work.Title != "" {
			title = ": " + in.Work.Title
		}
		b.WriteString("=== Рабочая память (подборка" + title + ") ===\n" + in.Work.Render() + "\n\n")
	}
	if in.Targets.Facts {
		f := in.Facts.Render()
		if f == "" {
			f = "(пусто)"
		}
		b.WriteString("=== Карточка фактов этой ветки ===\n" + f + "\n\n")
	}
	b.WriteString("=== Последние реплики разговора ===\n")
	tail := in.History
	if len(tail) > recentMessages {
		tail = tail[len(tail)-recentMessages:]
	}
	if r := Render(tail); r != "" {
		b.WriteString(r)
	} else {
		b.WriteString("(разговор только начинается)\n")
	}
	b.WriteString("\n=== Новая реплика пользователя ===\n" + strings.TrimSpace(in.User) + "\n")
	return b.String()
}

// repeatedAsks — о чём человек уже просил разово: увидев это, модель
// охотнее ставит "always" сама.
func repeatedAsks(p profile.Profile) string {
	var lines []string
	for key, n := range p.Asks {
		field, value, ok := strings.Cut(key, "=")
		if !ok || n < 1 {
			continue
		}
		lines = append(lines, fmt.Sprintf("- %s: %s — разовых просьб %d", field, profile.Label(field, value), n))
	}
	if len(lines) == 0 {
		return ""
	}
	return "О чём уже просили разово (повторная просьба — это предпочтение):\n" + strings.Join(lines, "\n") + "\n"
}
